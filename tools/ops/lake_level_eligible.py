#!/usr/bin/env python3
"""The customer Lake-level list = Lake's REVIEWED set (owner approval, Michael, 2026-11-20 20:01Z, Sector_Ops #51).

Every lake whose level binding is REVIEWED gets a customer level copy: the 5 hand-written pilots in
brains/lake/runtime/LakeBrain/LakeSourceBindings.swift plus jobs/lake-brain/data/accepted_batch.json and accepted_batch2.json. Each of them reads a real gauge
(an operator pool or a lake gauge). Lakes that are held, excluded or failed the two-gauge check (Brookville IN, Sumner NM) have no reviewed
binding, so they are never on the list.

The list lives in two places that a test keeps equal: the Publisher's JSON (customer_lake_level_eligible.json) and the Engine's Swift
LakeLevelEligibility.validatedLakeIds. This tool derives both from the reviewed set, so they cannot drift from it.

  python tools/ops/lake_level_eligible.py            # print the derived list (JSON)
  python tools/ops/lake_level_eligible.py --write    # rewrite the JSON lakeIds and the Swift validatedLakeIds block
  python tools/ops/lake_level_eligible.py --check    # exit 1 if either differs from the reviewed set

No network, no database. Everything else in the JSON (schema, notes) is kept as it is.
"""
from __future__ import annotations

import argparse
import json
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.normpath(os.path.join(HERE, "..", ".."))
BINDINGS_SWIFT = os.path.join(ROOT, "brains", "lake", "runtime", "LakeBrain", "LakeSourceBindings.swift")
ACCEPTED = os.path.join(ROOT, "jobs", "lake-brain", "data", "accepted_batch.json")
ACCEPTED2 = os.path.join(ROOT, "jobs", "lake-brain", "data", "accepted_batch2.json")   # batch 2 (2026-11-22), same format
ELIGIBLE = os.path.join(ROOT, "jobs", "brain_platform", "sector_brain_platform", "publisher_live", "customer_lake_level_eligible.json")
ENGINE_SWIFT = os.path.join(ROOT, "Sources", "SectorEngine", "API", "LakeLevelOutputAPI.swift")

APPROVAL = ("owner approval (Michael, 2026-11-20 20:01Z, Sector_Ops #51): the list is every lake with a REVIEWED binding "
            "(5 pilots + accepted_batch.json + accepted_batch2.json); TVA lakes are listed like any other lake, no operator-only class (owner decision, Michael, 2026-11-22 19:34Z, Sector_Ops #51 comment 7084511040); "
            "earlier: Sector_Ops #45 Lake Beta V1 + 4 TVA mainstem lakes operator-only (comment 7044052751)")
BEGIN = "    public static let validatedLakeIds: Set<String> = ["
END = "    ]"


def pilot_ids(path: str = BINDINGS_SWIFT) -> list[str]:
    """Lake ids of the hand-written REVIEWED pilots (LakeSourceBindings.handWritten)."""
    s = open(path, encoding="utf-8").read()
    block = s[s.index("static let handWritten"):s.index("public static let pilots")]
    ids = re.findall(r'tvaPilot\("([^"]+)"', block) + re.findall(r'lakeId: "([^"]+)", status: \.reviewed', block)
    if not ids:
        raise SystemExit("no pilots found in LakeSourceBindings.handWritten")
    return ids


def accepted_ids(path: str = ACCEPTED, path2: str = ACCEPTED2) -> list[str]:
    ids = list(json.load(open(path, encoding="utf-8"))["lakeIds"])
    if path2 and os.path.exists(path2):
        ids += json.load(open(path2, encoding="utf-8"))["lakeIds"]
    return ids


def derived() -> list[str]:
    return sorted(set(pilot_ids()) | set(accepted_ids()))


def swift_ids(path: str = ENGINE_SWIFT) -> set[str]:
    s = open(path, encoding="utf-8").read()
    block = s[s.index("validatedLakeIds: Set<String>"):]
    block = block[:block.index("\n    ]")]
    return set(re.findall(r'"([^"]+\|[A-Z]{2})"', block))


def swift_block(ids: list[str]) -> str:
    lines, cur = [], "       "
    for i in ids:
        tok = f' "{i}",'
        if len(cur) + len(tok) > 140:
            lines.append(cur)
            cur = "       "
        cur += tok
    lines.append(cur)
    head = ("        // GENERATED by tools/ops/lake_level_eligible.py from Lake's REVIEWED set (5 pilots + jobs/lake-brain/data/accepted_batch.json + accepted_batch2.json);\n"
            "        // do not hand-edit. Owner approval 2026-11-20 20:01Z (Sector_Ops #51).\n")
    return head + "\n".join(lines) + "\n"


def write(ids: list[str]) -> None:
    d = json.load(open(ELIGIBLE, encoding="utf-8"))
    d["lakeIds"] = ids
    d["approvalRef"] = APPROVAL
    d["source"] = ("Lake's REVIEWED bindings (5 pilots + jobs/lake-brain/data/accepted_batch.json + accepted_batch2.json), derived by tools/ops/lake_level_eligible.py; "
                   "mirrored in Sources/SectorEngine/API/LakeLevelOutputAPI.swift LakeLevelEligibility.validatedLakeIds (a test keeps them equal)")
    with open(ELIGIBLE, "w", encoding="utf-8") as f:
        json.dump(d, f, indent=2, ensure_ascii=False)
        f.write("\n")
    s = open(ENGINE_SWIFT, encoding="utf-8").read()
    a = s.index(BEGIN) + len(BEGIN) + 1
    b = s.index("\n" + END + "\n", a) + 1
    s = s[:a] + swift_block(ids) + s[b:]
    with open(ENGINE_SWIFT, "w", encoding="utf-8") as f:
        f.write(s)


def problems(ids: list[str]) -> list[str]:
    out = []
    j = json.load(open(ELIGIBLE, encoding="utf-8"))["lakeIds"]
    if j != ids:
        out.append(f"{ELIGIBLE}: lakeIds differ from the reviewed set ({len(j)} vs {len(ids)})")
    if swift_ids() != set(ids):
        out.append(f"{ENGINE_SWIFT}: validatedLakeIds differ from the reviewed set")
    return out


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    g = ap.add_mutually_exclusive_group()
    g.add_argument("--write", action="store_true")
    g.add_argument("--check", action="store_true")
    a = ap.parse_args(argv)
    ids = derived()
    if a.write:
        write(ids)
        print(f"wrote {len(ids)} lakes")
        return 0
    if a.check:
        p = problems(ids)
        for x in p:
            print("DRIFT:", x)
        print("OK" if not p else "FAIL", len(ids))
        return 1 if p else 0
    print(json.dumps(ids, indent=2))
    return 0


if __name__ == "__main__":
    sys.exit(main())
