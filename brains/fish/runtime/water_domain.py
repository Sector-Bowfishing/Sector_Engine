"""Water-domain identity metadata (FRESHWATER / BRACKISH / MARINE), resolved from the Species Registry.

The Species Registry (`platform/registries/species/species_water_domains.json`) is the ONLY authority. This module loads and validates its packaged
projection and projects it onto species summaries, exactly as `target_set.role` projects `productRole`. It never infers a classification, never defaults an unknown
to freshwater, and has no relationship to any score. Water domain is NOT a migration strategy (diadromy): never add DIADROMOUS here.
"""
from __future__ import annotations

from pathlib import Path

DOMAINS = ("FRESHWATER", "BRACKISH", "MARINE")            # canonical order
# Packaged PROJECTION of the registry (water_domain_registry.py, generated by tools/gen_water_domain_projection.py). The orchestrator image ships only
# runtime + platform, so the runtime cannot read platform/registries/. Tests assert the projection equals the Species Registry file, the sole authority.
CANONICAL_PATH = Path(__file__).resolve().parents[3] / "platform" / "registries" / "species" / "species_water_domains.json"
_cache: dict | None = None


def validate_entry(e: dict) -> list[str]:
    sid = e.get("speciesId")
    d, a = e.get("waterDomains"), e.get("assessment") or {}
    errs = []
    if a.get("status") == "UNKNOWN":
        if d is not None:
            errs.append(f"{sid}: UNKNOWN must have waterDomains null (never defaulted)")
    elif a.get("status") == "ASSESSED":
        if not isinstance(d, list) or not d:
            errs.append(f"{sid}: ASSESSED needs at least one water domain")
        else:
            if any(x not in DOMAINS for x in d):
                errs.append(f"{sid}: domain outside {DOMAINS}: {d}")
            if len(set(d)) != len(d):
                errs.append(f"{sid}: duplicate domains {d}")
            if [x for x in DOMAINS if x in d] != d:
                errs.append(f"{sid}: domains not in canonical order {d}")
        if not a.get("sources"):
            errs.append(f"{sid}: ASSESSED needs at least one source")
    else:
        errs.append(f"{sid}: bad assessment status {a.get('status')!r}")
    return errs


def validate_registry(doc: dict) -> list[str]:
    errs, ids = [], [s.get("speciesId") for s in doc.get("species", [])]
    errs += [f"duplicate speciesId {i}" for i in set(ids) if ids.count(i) > 1]
    if ids != sorted(ids):
        errs.append("species not sorted by speciesId (deterministic order)")
    for e in doc.get("species", []):
        errs += validate_entry(e)
    return errs


def load(doc: dict | None = None) -> dict:
    """speciesId -> registry entry. Fails closed on an invalid registry."""
    global _cache
    if doc is None and _cache is not None:
        return _cache
    if doc is None:
        from water_domain_registry import REGISTRY as doc
    errs = validate_registry(doc)
    if errs:
        raise ValueError("species water-domain registry invalid: " + "; ".join(errs))
    out = {e["speciesId"]: e for e in doc["species"]}
    if doc is not None and _cache is None:
        _cache = out
    return out


def project(species_id: str) -> dict:
    """Fields projected onto a species summary: {} when the species is not in the registry (not assessed), else waterDomains + waterDomainStatus.
    UNKNOWN keeps waterDomains absent (RTDB drops nulls); consumers render absent + status UNKNOWN as an em dash."""
    e = load().get(species_id)
    if e is None:
        return {}
    out = {"waterDomainStatus": e["assessment"]["status"]}
    if e["waterDomains"] is not None:
        out["waterDomains"] = list(e["waterDomains"])
    return out
