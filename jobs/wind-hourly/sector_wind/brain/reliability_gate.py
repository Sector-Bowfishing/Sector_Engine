"""Automatic evaluation of the 30-day PROSPECTIVE reliability gate (no human reminder needed).

Runs inside the existing hourly Brain publish (no new schedule). Until 30 complete UTC days have elapsed since the live clock started it is a cheap date
check that does nothing. The first run on/after the gate computes the canonical reliability dimension EXACTLY as the scorer does
(`scoreboard.dim8`: completeness over the full window, median availability age <= 90 min, fallbacks exercised), records the verdict ONCE at
`brain/wind/reliability_gate.json`, and raises one activity event. It never backfills or edits prospective days and never publishes a score:
the canonical score is still regenerated by the scorer and published by the shared orchestrator."""
from __future__ import annotations

from datetime import datetime, timedelta, timezone

from .. import scoreboard as SB

KEY = "brain/wind/reliability_gate.json"
TARGET_DAYS = 30


def gate_day() -> datetime:
    return SB.LIVE_START + timedelta(days=TARGET_DAYS)


def record_once(store, cfg, now: datetime):
    """-> (result | None, is_new). None until the gate day has passed; the stored result (is_new False) on every later run."""
    if now < gate_day():
        return None, False
    existing = store.get_json(KEY)
    if existing:
        return existing, False
    d = SB.dim8(store, cfg, now)
    conds = {k: round(v, 4) for k, v in d["conditions"].items()}
    passed = d["credit"] >= 1.0
    res = {"schema": "wind-reliability-gate-v1", "evaluatedAt": now.strftime("%Y-%m-%dT%H:%M:%SZ"), "targetDays": TARGET_DAYS, "window": d["window"],
           "hours": d["n"], "conditions": conds, "credit": round(d["credit"], 4), "verdict": "PASS" if passed else "FAIL",
           "failedConditions": sorted(k for k, v in conds.items() if v < 1.0), "why": d["why"],
           "note": "Prospective live archive only; nothing backfilled. Regenerate the canonical score artifact to publish the new dimension value."}
    store.put_json(KEY, res)
    return res, True
