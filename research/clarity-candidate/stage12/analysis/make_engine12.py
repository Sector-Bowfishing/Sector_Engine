"""Write analysis/engine12.py: the Part 4 final engine as a standalone classify(rho, sun) -> (class, ft) for the tandem
platform test (section 2 condition a). Fitted engines use the production fit on all selection rows (models12.json)."""
import json
D = __import__("os").environ["CLARITY_RESEARCH_ROOT"] + "/stage12"
M = json.load(open(f"{D}/analysis/models12.json")); E = M["final_engine"]
if E == "routed": E = M["engine"]      # the tandem test uses the single engine if routing were adopted (documented)
coef = M.get("engine_production_coef")
src = f'''"""Generated by make_engine12.py: final engine {E}."""
import math, sys
from common12 import dog, champ, cname, P1, P2, ndci
ENGINE = "{E}"; COEF = {coef!r}
def _feats(r, fnu):
    lr = math.log10(max(r["red"], 0.001)); nd = ndci(r)
    return {{"champion_refit": [1.0, math.log10(max(fnu, 0.1))], "N1": [1.0, lr],
             "N2": [1.0, lr, math.log10(max(r["green"], 0.001) / max(r["red"], 0.001))],
             "C3": [1 - (1.0 if nd > 0 else 0.0), (1 - (1.0 if nd > 0 else 0.0)) * lr, 1.0 if nd > 0 else 0.0, (1.0 if nd > 0 else 0.0) * lr],
             "C6": [1.0, lr, nd, nd * lr]}}.get(ENGINE)
def classify(b, sun):
    if any(not isinstance(b.get(k), float) or not math.isfinite(b[k]) for k in ("B02", "B03", "B04", "B05")): return ("unknown", None)
    r = {{"blue": b["B02"], "green": b["B03"], "red": b["B04"], "re1": b["B05"]}}; fnu = dog(r["red"])
    if ENGINE == "champion": ft = champ(fnu)
    elif ENGINE == "P1": ft = P1(r, sun)[0]
    elif ENGINE == "P2": ft = P2.route(r, sun, b.get("B11") if isinstance(b.get("B11"), float) and math.isfinite(b["B11"]) else 0.0)["ft"]
    else: ft = 10 ** sum(c * f for c, f in zip(COEF, _feats(r, fnu)))
    return (cname(ft), ft) if ft else ("unknown", None)
'''
open(f"{D}/analysis/engine12.py", "w").write(src); print("engine12.py for", E)
