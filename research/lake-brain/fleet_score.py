#!/usr/bin/env python3
"""Fleet research score for Lake Brain — the UNMODIFIED rubric (score_lake) over lakes whose evidence the research produced.

Inputs (all outside Git, regenerated by the binding / baselines threads):
  <DATA>/binding/verified.csv                 one row per directory lake: binding status, capability, history class, operator-plan levels
  <DATA>/history/tva_pilots/*.csv             deep TVA pilot history (NWS RVDHUN + HADS + CWMS), 16-18 complete years
Counting rules (pre-registered here, before the numbers were computed; stricter than the rubric requires):
  profiled   = bindingStatus in {VERIFIED, VERIFIED_CORROBORATED}      ('core': passes every binding-review-v1 check, not flagged)
               (+ optional --with-flagged: VERIFIED_FLAG; STAGE_ONLY and NONE never count; NO_SOURCE reviews never count)
  source     = capability in {DIRECT_OPERATOR_POOL, DIRECT_LAKE_GAUGE}  (all profiled lakes by construction)
  plan       = a seasonal guide curve (TVA guide, CWMS Guide/Rule Curve) OR a conservation zone with BOTH a top
               (Top of Conservation / Top of Normal) and a bottom (Bottom of Normal / Bottom of Conservation / Drought level)
  flood      = an operator-published flood-pool bottom: 'Top of Conservation' | 'Bottom of Flood' | 'Bottom of Flood Control'
  history    = SUFFICIENT (>= 5 complete years of daily values, >= 329 days/year) per the Lake Brain baseline rule;
               the 4 TVA pilots use the composite (re-counted here); the other TVA lakes are LIMITED (3.9 y of HADS)
  baseline   = SUFFICIENT or LIMITED
  trend      = every profiled lake publishes an observed level (live series fresh at probe time: R6)
Usage: fleet_score.py [--with-flagged] [--min-years N] [--json OUT]
"""
from __future__ import annotations

import argparse
import collections
import csv
import datetime as dt
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "tools"))
from research_score import score  # noqa: E402

DATA = os.path.expanduser("~/Desktop/Development/Sector_Research_Data/lake-brain")
TVA_PILOTS = {"Guntersville|AL": "GVDA1", "Wheeler|AL": "WHLA1", "Wilson|AL": "WLSA1", "Pickwick Lake|TN": "PICT1"}
GUIDE_WORDS = ("guide curve", "rule curve", "tva operating guide")
TOP_WORDS = ("top of conservation", "top of normal", "top con")
BOTTOM_WORDS = ("bottom of normal", "bottom of conservation", "drought", "bottom con")
FLOOD_WORDS = ("top of conservation", "bottom of flood", "top con")           # flood-pool bottom == top of conservation


def tva_years() -> dict[str, int]:
    out = {}
    for lake, loc in TVA_PILOTS.items():
        p = os.path.join(DATA, "history", "tva_pilots", f"{loc}_daily.csv")
        if not os.path.exists(p):
            continue
        by = collections.Counter(r["date"][:4] for r in csv.DictReader(open(p)))
        out[lake] = sum(1 for y, n in by.items() if n >= 329 and int(y) < dt.date.today().year)
    return out


def classify(row: dict, tva_pilot_years: dict[str, int], min_years: int) -> dict:
    plan_txt = (row.get("operatorPlan") or "").lower()
    has_guide = any(w in plan_txt for w in GUIDE_WORDS)
    has_zone = any(w in plan_txt for w in TOP_WORDS) and any(w in plan_txt for w in BOTTOM_WORDS)
    flood = any(w in plan_txt for w in FLOOD_WORDS)
    lake = row["lakeId"]
    years = int(float(row["completeYears"] or 0))
    hist = row["historyClass"]
    if lake in tva_pilot_years:
        years = tva_pilot_years[lake]; hist = "SUFFICIENT" if years >= 5 else "LIMITED"
    elif (row.get("provider") == "tva"):
        years, hist = 4, "LIMITED"                                           # HADS-only (3.9 y); SUFFICIENT in 2028
    if hist == "SUFFICIENT" and years < min_years:
        hist = "LIMITED"                                                     # sensitivity: stricter than the rubric's 5 y
    return {"src": row["capability"] in ("DIRECT_OPERATOR_POOL", "DIRECT_LAKE_GAUGE"), "plan": has_guide or has_zone,
            "guide": has_guide, "flood": flood, "hist": hist == "SUFFICIENT", "base": hist in ("SUFFICIENT", "LIMITED"), "years": years}


def main(argv=None) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--with-flagged", action="store_true")
    ap.add_argument("--min-years", type=int, default=5, help="sensitivity: require this many complete years for SUFFICIENT (rubric: 5)")
    ap.add_argument("--providers", default=None, help="comma list; only bindings from these providers count (e.g. tva,cwms,usgs = what the Engine can read today)")
    ap.add_argument("--json", default=None)
    a = ap.parse_args(argv)
    rows = list(csv.DictReader(open(os.path.join(DATA, "binding", "verified.csv"))))
    ok = {"VERIFIED", "VERIFIED_CORROBORATED"} | ({"VERIFIED_FLAG"} if a.with_flagged else set())
    prof = [r for r in rows if r["bindingStatus"] in ok and (not a.providers or r["provider"] in a.providers.split(","))]
    ty = tva_years()
    cl = [classify(r, ty, a.min_years) for r in prof]
    n = len(prof)
    share = lambda k: sum(1 for c in cl if c[k]) / n if n else 0.0  # noqa: E731
    shares = {"src": share("src"), "plan": share("plan"), "hist": share("hist"), "base": share("base"), "obs": 1.0, "flood": share("flood")}
    out = {"profiled": n, "profiledPct": round(100 * n / 621, 1), "shares": {k: round(v, 3) for k, v in shares.items()},
           "guideCurveShare": round(share("guide"), 3), "withFlagged": a.with_flagged, "minYears": a.min_years, "providers": a.providers or "all", "byProvider": dict(collections.Counter(r["provider"] for r in prof)), "tvaPilotYears": ty,
           "scores": {}}
    for v in ("NOT_VALIDATED", "PARTIAL", "VALIDATED"):
        s = score(621, n, shares, v)
        out["scores"][v] = {"value": s["value"], "uncapped": s["uncapped"], "gates": [g.get("gate") for g in s["scoreBlockers"] if g.get("gate")],
                            "dims": {k: x.get("value") for k, x in s["scoreBreakdown"].items()}}
    print(json.dumps(out, indent=1))
    if a.json:
        json.dump(out, open(a.json, "w"), indent=1)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
