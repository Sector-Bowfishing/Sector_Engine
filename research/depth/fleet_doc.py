"""Regenerate docs/brains/depth/DEPTH_CANDIDATE_FLEET.md (+ the flat CSV) from candidates.json and the progress log. Deterministic."""
import csv, json, os, collections, sys
ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
sys.path.insert(0, f"{ROOT}/jobs/depth-brain")
from depth_brain import maturity as M

man = json.load(open(f"{ROOT}/jobs/depth-brain/depth_brain/data/candidates.json"))
C = man["candidates"]
fm = M.fleet_metrics(man)
log = [json.loads(l) for l in open(f"{ROOT}/docs/brains/depth/data/depth_progress_log.jsonl") if l.strip()]
fields = ['lakeId','lakeName','state','operator','referencePoolFt','referenceDatum','referenceDatumVerified','referencePoolSource','referencePoolBasis','referencePoolConfidence','levelSourceStatus','levelProvider','levelCapability','levelDatum','historyCompleteYears','rangeClass','datumStatus','datumSigmaFt','datumEvidenceConfidence','shiftPossible','blockedReasons','rollout','depthTier','researchTier','contourLicence']
with open(f"{ROOT}/docs/brains/depth/data/depth_candidate_fleet.csv", "w", newline="") as f:
    w = csv.writer(f); w.writerow(fields)
    for c in C:
        w.writerow([c['lakeId'],c['lakeName'],c['state'],c['operator'],c['reference']['poolFt'],c['reference']['datum'],c['reference']['datumVerified'],(c['reference']['source'] or '')[:80],c['reference']['basis'],c['reference']['confidence'],c['levelSource']['status'],c['levelSource']['provider'],c['levelSource']['capability'],c['levelSource']['datum'],c['history']['completeYears'],c['history']['rangeClass'],c['datum']['status'],c['datum']['sigmaFt'],c['datum'].get('evidenceConfidence'),c['shiftPossible'],';'.join(c['blockedReasons']),c['rollout'],c['evidence']['tier'],c['evidence']['researchTier'],c['licence'].get('customerDerivedMetricsAllowed')])
pool = [c for c in C if c['reference']['basis'] == 'fullPool' and c['reference']['confidence'] in ('high', 'medium') and c['reference']['poolFt'] is not None]
bound = [c for c in pool if c['levelSource']['status'] != 'NONE']
ok = [c for c in C if c['shiftPossible']]
ds = collections.Counter(c['datum']['status'] for c in ok)
conf = collections.Counter(c['datum'].get('evidenceConfidence') or 'n/a' for c in ok)
ops = collections.Counter(c['operator'] for c in ok).most_common(10)
rc = collections.Counter(c['history']['rangeClass'] for c in ok)
base = log[0]["fleet"]
rows = "".join(f"| {e['cycle']} | {e['overall']} | {e['fleet']['shiftPossible']} | {e['fleet']['verifiedDatum']} | {e['fleet']['pilotVerified']}/{e['fleet']['highConfidence']}/{e['fleet']['mediumConfidence']}/{e['fleet']['blocked']} | {e['fleet'].get('effectiveZoneEligible')} |\n" for e in log)
md = f"""# Depth Shift Candidate Fleet (generated {log[-1]['at'][:10]})

Generated by `research/depth/fleet_doc.py` from `jobs/depth-brain/depth_brain/data/candidates.json` (manifest `{man.get('manifestVersion')}`) and `docs/brains/depth/data/depth_progress_log.jsonl`. Flat view: `docs/brains/depth/data/depth_candidate_fleet.csv` (621 rows). Do not edit by hand.

The research count (~265, and 339 "delta possible") assumed a bound level plus a pool figure was enough. The Depth count additionally requires a **provable datum relationship** (`DEPTH_DATUM_AUDIT.md`, `DEPTH_DATUM_PAIRING_RESULTS.md`), a direct level source and an accepted pool basis/confidence.

## Funnel ({fm['totalLakes']} directory lakes)

| Gate | Lakes |
|---|---|
| Directory pool is a pool elevation, confidence high/medium, figure present | {len(pool)} |
| ... and a verified Lake Brain level binding (research bindings + 5 live reviewed) | {len(bound)} |
| ... and a **defensible datum relationship** | **{len(ok)}** |
| Plausible but blocked (mostly datum) | {len(bound) - len(ok)} |

## Rollout tiers

| Tier | Lakes | Rule |
|---|---|---|
| PILOT_VERIFIED | {fm['pilotVerified']} | live reviewed Lake Brain binding and defensible datum |
| HIGH_CONFIDENCE | {fm['highConfidence']} | strong binding, high pool, SAME_SOURCE / SAME_OPERATOR_SYSTEM / SAME_DATUM with high datum evidence, >= 10 complete years, direct source |
| MEDIUM_CONFIDENCE | {fm['mediumConfidence']} | shift possible but medium-confidence datum evidence, labelled binding, medium pool, or < 10 years |
| BLOCKED | {fm['blocked']} | reasons in the CSV and `DEPTH_DATUM_UNLOCK_QUEUE.md` |

| Datum relationship of the {len(ok)} | Lakes |
|---|---|
| SAME_SOURCE (one operator record) | {ds.get('SAME_SOURCE', 0)} |
| SAME_DATUM (both stated and equal) | {ds.get('SAME_DATUM', 0)} |
| SAME_OPERATOR_SYSTEM (TVA, inferred, sigma 0.1) | {ds.get('SAME_OPERATOR_SYSTEM', 0)} |
| CONVERTED (disabled) | {ds.get('CONVERTED', 0)} |

Verified datum (SAME_SOURCE + SAME_DATUM): **{fm['verifiedDatum']}**; inferred operator system: **{fm['inferredOperatorSystem']}**. Datum evidence confidence among the defensible lakes: {dict(conf)}. Operators (top): {', '.join(f'{k} {v}' for k, v in ops)}. Operating range class: {dict(rc)}.

## Progress by cycle (research maturity is the RESEARCH rubric, NOT an official score)

| Cycle | Research maturity | Shift-defensible | Verified datum | Pilot/High/Medium/Blocked | Effective-zone eligible |
|---|---|---|---|---|---|
{rows}
Only the {fm['pilotVerified']} pilots can publish today: Lake Brain publishes `states/lake` for exactly those lakes. The rest become live when Lake Brain adopts fleet bindings; Depth then needs no change.

## Cautions carried in the data

* Hartwell's pool (660 ft) is the **summer** top of conservation; the winter guide is 656 ft (`DEPTH_HARTWELL_EFFECTIVE_DEPTH.md`). The state carries Lake Brain's `guideFt` / `differenceFromGuideFt` beside the shift.
* Pool-confidence `medium` lakes carry sigma >= 1.0 ft (shift rarely `resolvable`).
* SAME_SOURCE on a LOCAL CWMS location is a valid *shift* (both numbers share one local datum) but gives no absolute elevation.
* Medium-confidence datum evidence (pool figure matched by value to a CWMS level, location without datum stamp, circular pairing) can never reach HIGH_CONFIDENCE.
* Licence gating: contour-derived numbers are internal-only unless source terms allow customer derived use (`DEPTH_LICENSING_MATRIX.md`, `DEPTH_LICENSING_UNLOCK_QUEUE.md`).
"""
open(f"{ROOT}/docs/brains/depth/DEPTH_CANDIDATE_FLEET.md", "w").write(md)
print(len(ok), fm['verifiedDatum'], dict(conf))
