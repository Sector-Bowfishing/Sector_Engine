"""Value-free path inventory of a Brain RTDB export (Cortex 2.2 FD audit).

Reads an export (a local file the operator supplies; it is never committed) and emits ONLY normalized path shapes with node counts:
no values, no lake/species/user/event identifiers, no timestamps. Data-valued keys collapse to placeholders ({k} lake key, {id} species,
{uid} user, {event} activity event, {source} source id, {job} job id, {i} list index, {execution}, {key} any other data-valued key), so the inventory
is safe to commit and compare across exports.

    python verification/firebase/path_inventory.py EXPORT.json --out verification/fixtures/firebase/production-path-inventory-YYYY-MM-DD.json
"""
from __future__ import annotations

import argparse
import json
import re
import sys
from collections import Counter

# (path prefix as normalized segments) -> placeholder for the NEXT key
COLLECTIONS = {
    ("lakes",): "{k}", ("lakeFleet",): "{k}", ("snapshots",): "{k}", ("control", "fleet"): "{k}",
    ("species",): "{id}", ("lakes", "{k}", "speciesPresence"): "{id}",
    ("access", "opsUsers"): "{uid}", ("activity",): "{event}", ("sources",): "{source}",
    ("jobs",): "{job}", ("health", "jobs"): "{job}", ("health", "sources"): "{source}",
    ("control", "orchestratorV1", "executions"): "{execution}",
}
MAX_DEPTH = 5             # deeper shapes are Brain-internal payload schema (covered by each Brain's own contract tests), counted at depth 5
_DATALIKE = re.compile(r"^(\d|[0-9a-f]{8,}$|-|.*\d{4}-\d{2}-\d{2}|d-\d{8}T|tva_|cwms_)|^[A-Z]{2}_|^[a-z]+_[a-z0-9_]+$|^[A-Za-z0-9]{20,}$")
STRUCTURAL_MAX = 60       # a dict with more children than this whose keys look like data is a keyed collection


IDENTIFIERS: dict = {}    # key -> placeholder, filled from the export's own collections so an identifier is masked wherever it recurs


def _identifiers(export: dict) -> dict:
    ids = {}
    for k, v in (export.get("lakes") or {}).items():
        ids[k] = "{k}"
        for sp in ((v or {}).get("speciesPresence") or {}):
            ids[sp] = "{id}"
    ids.update({k: "{id}" for k in (export.get("species") or {})})
    ids.update({k: "{uid}" for k in ((export.get("access") or {}).get("opsUsers") or {})})
    ids.update({k: "{event}" for k in (export.get("activity") or {})})
    return ids


def _norm_children(prefix: tuple, node: dict) -> dict:
    ph = COLLECTIONS.get(prefix)
    if ph is None and any(k in IDENTIFIERS for k in node):
        return {k: IDENTIFIERS.get(k, k) for k in node}
    if ph is None and (len(node) > STRUCTURAL_MAX or (node and all(_DATALIKE.search(k) for k in node))):
        ph = "{key}"
    return {k: (ph or k) for k in node}


def walk(node, prefix: tuple, out: Counter, leaf: dict) -> None:
    out["/" + "/".join(prefix)] += 1
    if len(prefix) >= MAX_DEPTH:
        if not isinstance(node, (dict, list)):
            leaf.setdefault("/" + "/".join(prefix), set()).add("null" if node is None else type(node).__name__)
        return
    if isinstance(node, dict):
        for k, ph in _norm_children(prefix, node).items():
            walk(node[k], prefix + (ph,), out, leaf)
    elif isinstance(node, list):
        for v in node:
            walk(v, prefix + ("{i}",), out, leaf)
    else:
        t = "null" if node is None else type(node).__name__
        leaf.setdefault("/" + "/".join(prefix), set()).add(t)


def inventory(export: dict) -> dict:
    counts: Counter = Counter()
    leaf: dict = {}
    IDENTIFIERS.clear()
    IDENTIFIERS.update(_identifiers(export))
    walk(export, (), counts, leaf)
    return {
        "schema": "sector-brain-rtdb-path-inventory-v1",
        "note": "Value-free: normalized path shapes, node counts and leaf JSON types only. Generated by verification/firebase/path_inventory.py.",
        "paths": {p: {"count": counts[p], **({"types": sorted(leaf[p])} if p in leaf else {})} for p in sorted(counts) if p != "/"},
    }


def main(argv=None) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("export")
    ap.add_argument("--out")
    ap.add_argument("--captured", help="capture date label recorded in the inventory (YYYY-MM-DD)")
    a = ap.parse_args(argv)
    with open(a.export, encoding="utf-8") as fh:
        inv = inventory(json.load(fh))
    if a.captured:
        inv["captured"] = a.captured
    text = json.dumps(inv, indent=1, sort_keys=True) + "\n"
    if a.out:
        with open(a.out, "w", encoding="utf-8") as fh:
            fh.write(text)
    else:
        sys.stdout.write(text)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
